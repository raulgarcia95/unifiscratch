const mergeUnifiscratchMessages = messagesByLocale => {
    const merged = {};
    Object.keys(messagesByLocale).forEach(locale => {
        const language = locale.split('-')[0];
        merged[locale] = Object.assign(
            {},
            messagesByLocale[locale],
            unifiscratchMessages.en,
            unifiscratchMessages[language] || {},
            unifiscratchMessages[locale] || {}
        );
    });
    return merged;
};

